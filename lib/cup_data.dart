class CupConfig {
  static List<List<String>> groupsFor(CupType type) {
    switch (type) {
      case CupType.t20WorldCup:
        // Random groups every tournament — shuffle all 20 teams into 4 groups of 5
        final teams = List<String>.from(_t20WcTeams)..shuffle();
        return [
          teams.sublist(0, 5),
          teams.sublist(5, 10),
          teams.sublist(10, 15),
          teams.sublist(15, 20),
        ];
      case CupType.odiWorldCup:
        return [
          ['India', 'Australia', 'England', 'South Africa', 'New Zealand',
           'Pakistan', 'Bangladesh', 'Sri Lanka', 'Afghanistan', 'West Indies'],
        ];
      case CupType.asiaCup:
        return [
          ['India', 'Pakistan', 'Nepal'],
          ['Sri Lanka', 'Bangladesh', 'Afghanistan'],
        ];
      case CupType.championsTrophy:
        return [
          ['India', 'Pakistan', 'New Zealand', 'Bangladesh'],
          ['Australia', 'England', 'South Africa', 'Afghanistan'],
        ];
    }
  }

  static int advanceCountFor(CupType type) => switch (type) {
    CupType.odiWorldCup => 4,
    _ => 2,
  };

  static MatchFormat formatFor(CupType type) => switch (type) {
    CupType.t20WorldCup || CupType.asiaCup => MatchFormat.t20,
    _ => MatchFormat.odi,
  };

  static int oversFor(CupType type) => switch (type) {
    CupType.t20WorldCup || CupType.asiaCup => 20,
    _ => 50,
  };

  // Picks 18 randomly from each team's 30-player pool.
  // Captain is always included. All others are shuffled, 17 chosen.
  // groups is passed in so teamsFor uses the same teams as groupsFor.
  static List<TournamentTeam> teamsFor(CupType type, List<List<String>> groups) {
    final rng = Random();
    final names = groups.expand((g) => g).toSet();
    return names.map((name) {
      final pool = CupData.teamPool(name);
      if (pool.isEmpty) return TournamentTeam(name: name, players: const []);
      final captain = pool.firstWhere((p) => p.isCaptain, orElse: () => pool.first);
      final rest = pool.where((p) => !identical(p, captain)).toList()..shuffle(rng);
      return TournamentTeam(name: name, players: [captain, ...rest.take(17)]);
    }).toList();
  }
